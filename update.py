def payload_files():
    binary = base64.b64decode(PAYLOAD)
    if hashlib.sha256(binary).hexdigest() != PAYLOAD_SHA256:
        raise RuntimeError('Embedded package checksum mismatch; this update.py is damaged.')
    files = {}
    with zipfile.ZipFile(io.BytesIO(binary)) as archive:
        for member in archive.infolist():
            name = PurePosixPath(member.filename)
            if member.is_dir():
                continue
            if name.is_absolute() or '..' in name.parts or '\\' in member.filename:
                raise RuntimeError('Unsafe path in embedded package.')
            if name.name in {'.env', 'state.json', 'title_overrides.json', 'cdn_cooldown.json', 'update.py'}:
                raise RuntimeError('Embedded package attempts to replace a protected file.')
            data = archive.read(member)
            if name.suffix == '.py':
                ast.parse(data.decode('utf-8'), filename=str(name))
            files[str(name)] = data
    return files


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix='.update-', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'wb') as output:
            output.write(content)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def update_files(project, files):
    project.mkdir(parents=True, exist_ok=True)
    backup = project / '.update-backups' / (datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + uuid.uuid4().hex[:6])
    backup.mkdir(parents=True, mode=0o700)
    original = {}
    installed = []
    try:
        # Back up all affected existing files before modifying any of them.
        for name in files:
            destination = project / name
            if destination.is_symlink() or not destination.resolve().is_relative_to(project.resolve()):
                raise RuntimeError(f'Refusing to overwrite symlink/outside path: {name}')
            if destination.exists():
                saved = backup / name
                saved.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(destination, saved)
                original[name] = True
            else:
                original[name] = False
        for name, data in files.items():
            atomic_write(project / name, data)
            installed.append(name)
    except BaseException:
        for name in reversed(installed):
            if original[name]:
                shutil.copy2(backup / name, project / name)
            else:
                (project / name).unlink(missing_ok=True)
        raise
    (backup / 'manifest.json').write_text(json.dumps({'version': VERSION, 'files_existed': original}, indent=2))
    if not (project / '.env').exists():
        atomic_write(project / '.env', files['.env.example'])
        print('Created .env from the example. Add your token locally before starting the bot.')
    return backup


def execute(command, project, log):
    print('Running:', ' '.join(map(str, command)), flush=True)
    with log.open('a', encoding='utf-8') as output:
        output.write('\n$ ' + ' '.join(map(str, command)) + '\n')
        output.flush()
        process = subprocess.Popen(list(map(str, command)), cwd=project, stdout=subprocess.PIPE,
                                   stderr=subprocess.STDOUT, text=True, errors='replace')
        try:
            for line in process.stdout:
                print(line, end='', flush=True)
                output.write(line)
                output.flush()
            code = process.wait()
        except BaseException:
            process.terminate()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
            raise
    if code:
        raise RuntimeError(f'Command failed with exit code {code}. See {log}')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--project', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--with-system-deps', action='store_true', help='Install FFmpeg, venv and Chromium OS libraries on apt-based Linux.')
    parser.add_argument('--test-source', nargs=3, metavar=('MAL_ID','LANGUAGE','EPISODE'), help='Also test yt-dlp access to a real manifest; no full episode download.')
    parser.add_argument('--cooldown-seconds', type=int, default=0, help='Seed/extend a CDN cooldown after a known HTTP 429; does not shorten an existing pause.')
    parser.add_argument('--files-only', action='store_true', help='Only back up and replace project files; do not install or run checks.')
    parser.add_argument('--verify-only', action='store_true', help='Validate the embedded package without changing anything.')
    args = parser.parse_args()
    if not 0 <= args.cooldown_seconds <= 86400:
        parser.error('--cooldown-seconds must be between 0 and 86400.')
    if args.cooldown_seconds and args.test_source:
        parser.error('Do not combine a cooldown with a live --test-source request. Test the source later, after the cooldown.')
    if sys.version_info < (3, 10):
        raise SystemExit('Python 3.10+ required. Run this updater with a supported Python interpreter.')
    files = payload_files()
    if args.verify_only:
        print(f'Embedded package verified: {len(files)} files; version {VERSION}; SHA-256 {PAYLOAD_SHA256}')
        return
    project = args.project.expanduser().resolve()
    print('STOP the running bot before updating. Destination:', project, flush=True)
    if not (project / 'bot.py').exists():
        raise SystemExit('No bot.py in destination. Specify --project /path/to/megaplay-selfbot.')
    backup = update_files(project, files)
    print(f'Replaced {len(files)} project files. Backup: {backup}')
    print('.env, resume state and local title overrides were not overwritten.')
    if args.files_only:
        print('FILES ONLY: dependency installation and runtime checks were skipped. Setup is not yet verified.')
        return
    logs = project / 'logs'
    logs.mkdir(exist_ok=True)
    log = logs / 'update.log'
    log.touch(mode=0o600, exist_ok=True)
    try:
        if args.cooldown_seconds:
            cooldown_path = project / 'cdn_cooldown.json'
            existing = json.loads(cooldown_path.read_text()) if cooldown_path.exists() else {}
            until = float(existing.get('until', 0))
            if not math.isfinite(until):
                raise RuntimeError('Invalid saved CDN cooldown timestamp. Inspect cdn_cooldown.json.')
            existing.update({'until': max(until, time.time() + args.cooldown_seconds), 'reason': 'HTTP 429 cooldown requested during update'})
            atomic_write(cooldown_path, (json.dumps(existing) + '\n').encode())
            print(f'CDN cooldown saved: at least {args.cooldown_seconds} seconds from now. Browser/dependency checks do not request the CDN.')
        if args.with_system_deps:
            if not sys.platform.startswith('linux') or not shutil.which('apt-get'):
                raise RuntimeError('--with-system-deps requires apt-based Linux. Install FFmpeg and Chromium OS libraries manually on this OS.')
            prefix = [] if hasattr(os, 'geteuid') and os.geteuid() == 0 else ['sudo']
            if prefix and not shutil.which('sudo'):
                raise RuntimeError('Root or sudo is required to install OS packages.')
            execute(prefix + ['apt-get', 'update'], project, log)
            execute(prefix + ['apt-get', 'install', '-y', 'ffmpeg', 'python3-venv', 'ca-certificates'], project, log)
        venv = project / '.venv'
        python = venv / ('Scripts/python.exe' if os.name == 'nt' else 'bin/python')
        if not python.exists():
            execute([sys.executable, '-m', 'venv', str(venv)], project, log)
        execute([python, '-m', 'pip', 'install', '--upgrade', 'pip'], project, log)
        # These packages share the discord namespace and must not coexist with self.
        execute([python, '-m', 'pip', 'uninstall', '-y', 'discord', 'discord.py', 'py-cord'], project, log)
        execute([python, '-m', 'pip', 'install', '--upgrade', '-r', 'requirements.txt'], project, log)
        execute([python, '-m', 'pip', 'install', '--force-reinstall', '--no-deps', 'discord.py-self==2.1.0'], project, log)
        browser_command = [python, '-m', 'playwright', 'install']
        if args.with_system_deps:
            browser_command.append('--with-deps')
        execute(browser_command + ['chromium'], project, log)
        execute([python, '-m', 'compileall', '-q', 'bot.py', 'media.py', 'resolver.py', 'metadata.py', 'diagnostics.py', 'doctor.py', 'downloader.py', 'rate_limits.py'], project, log)
        check = [python, 'doctor.py']
        if args.test_source:
            check += ['--source', *args.test_source]
        execute(check, project, log)
    except (RuntimeError, OSError) as exc:
        print('\nUPDATE NOT READY:', exc, file=sys.stderr)
        print('Source files were updated, but installation/checks did not pass. Do not treat this as a working setup.', file=sys.stderr)
        print('Backup:', backup, file=sys.stderr)
        print('Share logs/doctor-report.json if created, or the last error in logs/update.log. Never share .env.', file=sys.stderr)
        raise SystemExit(1)
    print('\nUPDATE AND CHECKS PASSED. This does not test Discord account access or full uploads.')
    print('Start using the virtual-environment interpreter (not global python3):')
    print(f'  {python} {project / "bot.py"}')
    print('Single-episode Discord test: .download 21 dub 1 1 (waits for any saved CDN cooldown).')
    print('HTTP 429 handling is now paced and fail-closed; this does NOT guarantee the provider will lift your IP rate limit.')


if __name__ == '__main__':
    main()
